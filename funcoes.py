"""
Crie um programa com uma função que receba dois 
numeros e 
imprima na tela a soma deles
"""
#Funções
def soma(a,b):
    resultado = a + b
    print(f"A soma é: {resultado}")

#Entrada
num1=float(input(f"Digite o num 1: "))
num2=float(input(f"Digite o num 2: "))

#Processamento
soma(num1, num2)

